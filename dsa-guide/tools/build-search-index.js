#!/usr/bin/env node
/* Builds assets/js/search-index.js by crawling the HTML pages.
   One record per heading-section (so results deep-link to anchors),
   plus one page-level record per page. Output is a JS file that sets
   window.SEARCH_INDEX = [...] — loaded via <script> so search works at
   file:// (where fetch() of local JSON is blocked).

   Run from the project root after editing content:
     node tools/build-search-index.js
*/
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const FILES = [
  "index.html",
  "foundations/index.html", "foundations/big-o.html", "foundations/arrays-strings.html",
  "foundations/linked-lists.html", "foundations/trees-graphs.html",
  "patterns/index.html", "patterns/arrays-hashing.html", "patterns/two-pointers.html",
  "patterns/sliding-window.html", "patterns/stack.html", "patterns/binary-search.html",
  "patterns/linked-list.html", "patterns/trees-traversal.html", "patterns/heap-topk.html",
  "patterns/backtracking.html", "patterns/graphs.html", "patterns/dynamic-programming.html",
  "patterns/intervals.html",
  "reference/cheatsheet.html",
];

function decode(s) {
  return s
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/&ldquo;|&rdquo;/g, '"').replace(/&mdash;|&ndash;/g, "-")
    .replace(/&nbsp;|&ensp;|&emsp;/g, " ").replace(/&rarr;/g, "->")
    .replace(/&hellip;/g, "...").replace(/&[a-z]+;/g, " ");
}
function strip(html) {
  return html
    .replace(/<svg[\s\S]*?<\/svg>/gi, " ")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ");
}
function clean(s) { return decode(strip(s || "")).replace(/\s+/g, " ").trim(); }
function tokens(text) {
  const set = new Set();
  (text.match(/[A-Za-z_][A-Za-z0-9_]+|\b\d{3}\b/g) || []).forEach(function (w) {
    if (w.length >= 2) set.add(w);
  });
  return Array.from(set);
}

const records = [];
for (const rel of FILES) {
  const html = fs.readFileSync(path.join(ROOT, rel), "utf8");
  const title = decode(((html.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || rel).split("|")[0]).trim();
  const bodyTag = (html.match(/<body[^>]*>/) || [""])[0];
  let tool = (bodyTag.match(/data-tool="([^"]+)"/) || [])[1];
  if (!tool) tool = rel.indexOf("reference/") === 0 ? "reference" : "home";

  // page-level record (hero h1 + lead)
  const heroH1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1] || title;
  const lead = (html.match(/<p class="lead"[^>]*>([\s\S]*?)<\/p>/) || [])[1] || "";
  const heroClean = clean(heroH1);
  records.push({
    url: rel, page: title, section: heroClean, tool,
    text: clean(heroH1 + " " + lead).slice(0, 300),
    keywords: tokens(heroClean.toLowerCase()),
  });

  // section records (anchored)
  const secRe = /<section[^>]*\bid="([^"]+)"[^>]*>([\s\S]*?)<\/section>/g;
  let m;
  while ((m = secRe.exec(html))) {
    const id = m[1], inner = m[2];
    const headRaw = (inner.match(/<h[23][^>]*>([\s\S]*?)<\/h[23]>/) || [])[1] || id;
    const head = clean(headRaw).replace(/^\d+\s*/, "");
    const codeWords = [];
    let cm; const codeRe = /<code[^>]*>([\s\S]*?)<\/code>/g;
    while ((cm = codeRe.exec(inner))) codeWords.push(clean(cm[1]));
    const kw = Array.from(new Set(
      tokens(head.toLowerCase()).concat(tokens(codeWords.join(" ")))
    )).slice(0, 40);
    records.push({
      url: rel + "#" + id, page: title, section: head, tool,
      text: clean(inner).slice(0, 300), keywords: kw,
    });
  }
}

const out = "/* GENERATED by tools/build-search-index.js — do not edit by hand. */\n" +
  "window.SEARCH_INDEX = " + JSON.stringify(records) + ";\n";
fs.writeFileSync(path.join(ROOT, "assets/js/search-index.js"), out);
console.log("Wrote", records.length, "records to assets/js/search-index.js");
